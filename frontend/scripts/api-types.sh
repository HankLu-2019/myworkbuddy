#!/usr/bin/env bash
# Generate src/api-schema.ts from the backend's OpenAPI schema (07 §8). `--check` fails when it is stale (CI).
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
(cd "$here/../backend" && uv run --frozen python scripts/openapi.py "$tmp/openapi.json" >/dev/null)
npx --no-install openapi-typescript "$tmp/openapi.json" -o "$tmp/api-schema.ts" >/dev/null
{
  echo "// Generated by scripts/api-types.sh from the backend's OpenAPI schema. Do not edit; run npm run api:types."
  cat "$tmp/api-schema.ts"
} > "$tmp/out.ts"
if [ "${1:-}" = "--check" ]; then
  if ! diff -u "$here/src/api-schema.ts" "$tmp/out.ts"; then
    echo "src/api-schema.ts is out of date: run 'npm run api:types' and commit the result." >&2
    exit 1
  fi
else
  cp "$tmp/out.ts" "$here/src/api-schema.ts"
fi
